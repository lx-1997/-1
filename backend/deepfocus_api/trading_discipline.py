def lookup(topic: Optional[str] = None, question: Optional[str] = None) -> dict[str, Any]:
    """按主题或问题关键词取纪律条目;都为空时返回全部主题概览。"""
    keys: list[str] = []
    t = (topic or "").strip().lower()
    if t in TOPICS:
        keys.append(t)
    q = (question or "").strip()
    if q:
        for key, words in _KEYWORDS:
            if key not in keys and any(w in q for w in words):
                keys.append(key)
    if not keys:  # 概览:每主题给标题+第一条
        return {
            "overview": [{"topic": k, "title": v["title"], "headline": v["rules"][0]} for k, v in TOPICS.items()],
            "note": "可用 topic 参数取单个主题的完整纪律(entry/sizing/add/stop/profit/bias/valuation_trap/review)。",
            "disclaimer": DISCLAIMER,
        }
    sections = [{"topic": k, **TOPICS[k]} for k in keys[:3]]  # 最多3个主题,防淹没
    return {"sections": sections, "disclaimer": DISCLAIMER}
